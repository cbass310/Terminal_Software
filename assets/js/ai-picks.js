// --- AUTO-ROTATION DISABLED (User-Controlled via Sports.js Dropdown) ---
let slipRotationInterval;

function startSlipRotation() {
    // Rotation intentionally disabled so users can select slips manually 
    // without the UI snapping away while they read the AI Rationale.
    if (typeof slipRotationInterval !== 'undefined' && slipRotationInterval) {
        clearInterval(slipRotationInterval);
    }
}

// We leave the listener but call the kill function to ensure 
// any lingering rotations are cleared out.
document.addEventListener('DOMContentLoaded', () => {
    setTimeout(startSlipRotation, 2000); 
});

